const BWRAP: &str = "/usr/bin/bwrap";
const BOOTSTRAP_PATH: &str = "/rush-sandbox-init";
const BOOTSTRAP_ARG: &str = "--__rush_sandbox_bootstrap_v1";
const PROBE_PATH: &str = "/rush-sandbox-probe";
const PROBE_ARG: &str = "--__rush_sandbox_seccomp_probe_v1";
const BOOTSTRAP_FD: RawFd = 4;
const CONTROL_FD: RawFd = 5;
const FIRST_CHILD_FD: RawFd = 16;
const MAX_POLICY_BYTES: usize = 1 << 20;

const RUNTIME_DIRS: &[&str] = &["/usr/lib", "/usr/lib64", "/lib", "/lib64", "/usr/share"];

// These are the small set of host configuration files needed by ordinary
// dynamically linked programs.  In particular, this is not /etc wholesale:
// credentials, user configuration, and host sockets stay outside the mount
// namespace unless the manifest explicitly grants a path.
const RUNTIME_FILES: &[&str] = &[
    "/etc/ld.so.cache",
    "/etc/ssl",
    "/etc/localtime",
    "/etc/nsswitch.conf",
    "/etc/passwd",
    "/etc/group",
];

/// The only data the trusted bootstrap accepts from the parent.
///
/// This is intentionally a private type.  It is generated by this module,
/// sealed in a memfd, and validated again after the re-exec.  There is no
/// privilege or mount request in this format for the child to interpret.
#[derive(Debug, Deserialize, Serialize)]
struct Policy {
    program: String,
    argv: Vec<String>,
    current_dir: String,
    env: Vec<(String, String)>,
    proxy_port: u16,
}

impl Policy {
    fn validate(&self) -> io::Result<()> {
        if self.program.is_empty()
            || !gopath::is_abs(&self.program)
            || self.program.as_bytes().contains(&0)
            || self.argv.is_empty()
            || self.argv[0] != self.program
            || self.current_dir.is_empty()
            || !gopath::is_abs(&self.current_dir)
            || self.current_dir.as_bytes().contains(&0)
        {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "invalid Linux sandbox policy paths",
            ));
        }
        let mut bytes = 0usize;
        for arg in &self.argv {
            if arg.as_bytes().contains(&0) {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidData,
                    "sandbox argv contains NUL",
                ));
            }
            bytes = bytes.saturating_add(arg.len());
        }
        for (key, value) in &self.env {
            if key.is_empty()
                || key.contains('=')
                || key.as_bytes().contains(&0)
                || value.as_bytes().contains(&0)
            {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidData,
                    "invalid sandbox environment entry",
                ));
            }
            bytes = bytes.saturating_add(key.len()).saturating_add(value.len());
        }
        if bytes > MAX_POLICY_BYTES {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "sandbox policy is too large",
            ));
        }
        Ok(())
    }
}

/// Bubblewrap must be a fixed, trusted system executable and all of the
/// namespace features used by `command` must work.  The result is cached: this
/// function is used by the plugin list/check/approval paths as well as launch.
pub(super) fn supported() -> Result<(), String> {
    static RESULT: OnceLock<Result<(), String>> = OnceLock::new();
    RESULT.get_or_init(probe_bwrap).clone()
}

fn probe_bwrap() -> Result<(), String> {
    let path = Path::new(BWRAP);
    let md = std::fs::metadata(path).map_err(|e| {
        format!(
            "plugins need Linux bubblewrap at {BWRAP}: {}",
            gopath::errno_text(&e)
        )
    })?;
    if !md.is_file() {
        return Err(format!("plugins need Linux bubblewrap at {BWRAP}"));
    }

    let current_exe = rush_sys::selfexe::path()
        .map_err(|e| format!("can't find rush executable for the Linux sandbox probe: {e}"))?;
    let current_exe = std::fs::canonicalize(current_exe)
        .map_err(|e| format!("can't resolve rush executable for the Linux sandbox probe: {e}"))?;

    // Execute only the fixed current executable in its constructor's seccomp
    // probe mode.  No plugin path, caller environment, host home, or caller
    // descriptor is intentionally made available.  The dynamic loader's
    // minimum runtime is mounted because `/usr/bin/true` alone would not be a
    // valid probe on a GNU host.  AppArmor/userns denial and missing
    // SECCOMP_FILTER_FLAG_NEW_LISTENER therefore fail closed here.
    let current_exe_arg = gopath::s(&current_exe);
    let mut cmd = Command::new(BWRAP);
    cmd.args([
        "--unshare-user",
        "--unshare-pid",
        "--unshare-net",
        "--unshare-ipc",
        "--unshare-uts",
        "--die-with-parent",
        "--ro-bind",
        "/usr",
        "/usr",
        "--ro-bind-try",
        "/lib",
        "/lib",
        "--ro-bind-try",
        "/lib64",
        "/lib64",
        "--ro-bind-try",
        "/etc/ld.so.cache",
        "/etc/ld.so.cache",
        "--ro-bind",
        // The current executable contains this constructor.  Its probe mode
        // installs a NEW_LISTENER filter and exits without running main.
        // The source path is appended below because this slice is all `&str`.
    ])
    .arg(current_exe_arg)
    .args([
        PROBE_PATH,
        "--proc",
        "/proc",
        "--dev",
        "/dev",
        "--remount-ro",
        "/proc",
        "--remount-ro",
        "/",
        "--",
        PROBE_PATH,
        PROBE_ARG,
    ])
    .env_clear()
    .current_dir("/")
    .stdin(Stdio::null())
    .stdout(Stdio::null())
    .stderr(Stdio::piped());
    super::keep_only_stdio(&mut cmd);
    let mut child = cmd
        .spawn()
        .map_err(|e| format!("can't probe Linux bubblewrap: {e}"))?;
    let mut stderr = Vec::new();
    if let Some(pipe) = child.stderr.take() {
        // Bubblewrap's diagnostics are useful for AppArmor/userns failures,
        // but never let a broken helper make support detection unbounded.
        let _ = pipe.take(4097).read_to_end(&mut stderr);
    }
    let status = child
        .wait()
        .map_err(|e| format!("can't wait for Linux bubblewrap probe: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        let detail = String::from_utf8_lossy(&stderr);
        let detail = detail.trim();
        let detail = if detail.is_empty() {
            String::new()
        } else {
            format!(": {detail}")
        };
        Err(format!(
            "Linux bubblewrap cannot create the required user/network/seccomp sandbox (status {status}){detail}; refusing to run plugins"
        ))
    }
}

/// Build the outer bubblewrap command.  The plugin itself is not started by
/// this command: bubblewrap first re-execs this process at `BOOTSTRAP_PATH`,
/// where the constructor installs the process filter and performs the final
/// approved-program exec.
pub(super) fn command(launch: &super::Launch) -> Result<Command, String> {
    supported()?;

    if launch.plugin.dir.is_empty() {
        return Err("Linux sandbox requires an installed plugin directory".into());
    }

    let plugin_dir = canonical_required("plugin directory", Path::new(&launch.plugin.dir))?;
    let plugin_alias = gopath::clean(&launch.plugin.dir);
    let data_path = crate::data_dir(&launch.plugin.name);
    crate::mkdir_all(&data_path.join("tmp"))?;
    let data_dir = canonical_required("plugin data directory", &data_path)?;
    let data_alias = gopath::s(&data_path);
    let program = launch.program()?;
    let current_exe = rush_sys::selfexe::path()
        .map_err(|e| format!("find rush executable for sandbox bootstrap: {e}"))?;
    let current_exe = canonical_required("rush executable", &current_exe)?;

    let env = launch
        .env()
        .into_iter()
        .map(|entry| {
            let (key, value) = entry
                .split_once('=')
                .ok_or_else(|| "sandbox environment entry has no '='".to_string())?;
            if key.is_empty() || key.contains('=') || key.as_bytes().contains(&0) {
                return Err("sandbox environment has an invalid name".to_string());
            }
            if value.as_bytes().contains(&0) {
                return Err(format!("sandbox environment {key} contains NUL"));
            }
            Ok((key.to_string(), value.to_string()))
        })
        .collect::<Result<Vec<_>, String>>()?;

    let mut argv = launch.plugin.command.clone();
    if argv.is_empty() {
        return Err("plugin command is empty".into());
    }
    argv[0] = program.clone();
    let policy = Policy {
        program: program.clone(),
        argv,
        current_dir: plugin_dir.clone(),
        env,
        proxy_port: launch.proxy_port,
    };
    policy.validate().map_err(|e| e.to_string())?;

    let policy_fd = sealed_policy(&policy).map_err(|e| format!("create sandbox policy: {e}"))?;
    let control = transport::channel(launch.proxy_port)
        .map_err(|e| format!("create sandbox control channel: {e}"))?;
    let devnull = OpenOptions::new()
        .read(true)
        .write(true)
        .custom_flags(libc::O_CLOEXEC)
        .open("/dev/null")
        .map_err(|e| format!("open sandbox fd 3: {e}"))?;

    let policy_source = duplicate_high(policy_fd.as_raw_fd())
        .map_err(|e| format!("duplicate sandbox policy: {e}"))?;
    let control_source = duplicate_high(control.as_raw_fd())
        .map_err(|e| format!("duplicate sandbox control: {e}"))?;
    let stdio_source =
        duplicate_high(devnull.as_raw_fd()).map_err(|e| format!("duplicate sandbox fd 3: {e}"))?;

    let mut mounts = MountPlan::new();
    add_runtime_mounts(&mut mounts);
    for requested in &launch.plugin.read {
        let path = manifest_path(requested)?;
        validate_optional_grant(&path)?;
        if path == "/" {
            return Err("a plugin read grant may not replace the synthetic root".into());
        }
        let canonical = canonical_existing(&path).unwrap_or_else(|| path.clone());
        if under(&path, &plugin_dir)
            || under(&canonical, &plugin_dir)
            || under(&path, &data_dir)
            || under(&canonical, &data_dir)
        {
            continue;
        }
        mounts.optional_ro(&path);
    }

    // Requested read mounts are parent-first. The plugin mount below overlays
    // them, while the data mount is restored after explicit write grants so a
    // broad approved read/write ancestor cannot turn data into the wrong host
    // tree or make it read-only.
    mounts.required_ro(&plugin_dir, &plugin_dir)?;
    if plugin_alias != plugin_dir && gopath::is_abs(&plugin_alias) {
        mounts.required_ro(&plugin_dir, &plugin_alias)?;
    }
    for requested in &launch.plugin.write {
        let path = manifest_path(requested)?;
        validate_optional_grant(&path)?;
        if path == "/" {
            return Err("a plugin write grant may not replace the synthetic root".into());
        }
        let canonical = canonical_existing(&path).unwrap_or_else(|| path.clone());
        // A path below data is already covered by the one writable data bind.
        if under(&path, &data_dir) || under(&canonical, &data_dir) {
            continue;
        }
        mounts.optional_rw(&path);
    }
    mounts.rw(&data_dir, &data_dir)?;
    if data_alias != data_dir && gopath::is_abs(&data_alias) {
        mounts.rw(&data_dir, &data_alias)?;
    }

    // A program and its literal shebang interpreter paths are always read
    // only, even if an explicit write path or broad read path covers them.
    if !under(&program, &plugin_dir) {
        mounts.required_ro(&program, &program)?;
    }
    for (interpreter, literal_path) in script_interpreters(Path::new(&program))? {
        if !under(&literal_path, &plugin_dir) {
            mounts.required_ro(&interpreter, &literal_path)?;
        }
    }
    // Keep the trusted bootstrap last: an approved broad path must never
    // replace the file that runs before the plugin filter is installed.
    mounts.required_ro(&current_exe, BOOTSTRAP_PATH)?;

    // bwrap's root is synthetic.  These two private mounts are created before
    // the final non-recursive root remount, so their intended child mount
    // permissions remain intact.  We intentionally do not pass --new-session:
    // the caller's process-group lifecycle is part of the plugin contract.
    mounts.directory("/proc");
    mounts.args.push("--proc".into());
    mounts.args.push("/proc".into());
    mounts.directory("/dev");
    mounts.args.push("--dev".into());
    mounts.args.push("/dev".into());
    mounts.args.push("--remount-ro".into());
    mounts.args.push("/proc".into());
    mounts.args.push("--remount-ro".into());
    mounts.args.push("/".into());

    mounts.args.push("--chdir".into());
    mounts.args.push(plugin_dir.clone());
    mounts.args.push("--".into());
    mounts.args.push(BOOTSTRAP_PATH.into());
    mounts.args.push(BOOTSTRAP_ARG.into());

    let mut cmd = Command::new(BWRAP);
    cmd.args(&mounts.args)
        .env_clear()
        .current_dir("/")
        .process_group(0)
        .stdin(Stdio::inherit())
        .stdout(Stdio::inherit())
        .stderr(Stdio::inherit());
    super::keep_only_stdio(&mut cmd);

    // `bwrap` 0.9 on Ubuntu 24.04 has no --preserve-fds option.  Descriptors
    // 3, 4 and 5 are inherited with CLOEXEC cleared only in this pre_exec
    // mapping; all source descriptors are >=16 and CLOEXEC, so neither bwrap
    // nor the plugin can accidentally receive the parent's other handles.
    unsafe {
        cmd.pre_exec(move || {
            for (source, target) in [
                (stdio_source.as_raw_fd(), 3),
                (policy_source.as_raw_fd(), BOOTSTRAP_FD),
                (control_source.as_raw_fd(), CONTROL_FD),
            ] {
                if libc::dup2(source, target) < 0 {
                    return Err(io::Error::last_os_error());
                }
                let flags = libc::fcntl(target, libc::F_GETFD);
                if flags < 0 || libc::fcntl(target, libc::F_SETFD, flags & !libc::FD_CLOEXEC) < 0 {
                    return Err(io::Error::last_os_error());
                }
            }
            Ok(())
        });
    }
    Ok(cmd)
}

/// A single mount plan keeps all destination creation inside the synthetic
/// root.  It never creates a host parent for a missing approved path.
struct MountPlan {
    args: Vec<String>,
    directories: HashSet<String>,
    targets: HashSet<String>,
}

impl MountPlan {
    fn new() -> Self {
        Self {
            args: vec![
                "--unshare-user".into(),
                "--unshare-pid".into(),
                "--unshare-net".into(),
                "--unshare-ipc".into(),
                "--unshare-uts".into(),
                "--die-with-parent".into(),
            ],
            directories: HashSet::new(),
            targets: HashSet::new(),
        }
    }

    fn directory(&mut self, path: &str) {
        let path = gopath::clean(path);
        let mut current = PathBuf::from("/");
        for component in Path::new(&path).components() {
            if let std::path::Component::Normal(name) = component {
                current.push(name);
                let current = gopath::s(&current);
                if self.directories.insert(current.clone()) {
                    self.args.push("--dir".into());
                    self.args.push(current);
                }
            }
        }
    }

    fn destination(&mut self, source: &str, destination: &str) {
        let md = std::fs::metadata(source);
        if md.as_ref().is_ok_and(|m| m.is_dir()) {
            self.directory(destination);
        } else if let Some(parent) = Path::new(destination).parent() {
            self.directory(&gopath::s(parent));
        }
    }

    fn required_ro(&mut self, source: &str, destination: &str) -> Result<(), String> {
        validate_mount_source(source)?;
        if destination == "/" {
            return Err("a plugin mount may not replace the synthetic root".into());
        }
        // Required mounts are also used for the final trusted executable and
        // approved program.  Append them even when a broad manifest grant
        // named the same destination: the final bind must win.
        self.targets.insert(destination.into());
        self.destination(source, destination);
        self.args
            .extend(["--ro-bind".into(), source.into(), destination.into()]);
        Ok(())
    }

    fn required_rw(&mut self, source: &str, destination: &str) -> Result<(), String> {
        validate_mount_source(source)?;
        if destination == "/" {
            return Err("a plugin mount may not replace the synthetic root".into());
        }
        if !self.targets.insert(destination.into()) {
            return Ok(());
        }
        self.destination(source, destination);
        self.args
            .extend(["--bind".into(), source.into(), destination.into()]);
        Ok(())
    }

    fn optional_ro(&mut self, path: &str) {
        let Some(source) = canonical_existing(path) else {
            return;
        };
        if validate_mount_source(&source).is_err() {
            return;
        }
        // Keep the approved spelling usable as well as the canonical target;
        // both binds point at the same canonical host object and neither
        // exposes its host parent directory.
        self.optional_ro_at(&source, path);
        if source != path {
            self.optional_ro_at(&source, &source);
        }
    }

    fn optional_rw(&mut self, path: &str) {
        let Some(source) = canonical_existing(path) else {
            return;
        };
        if validate_mount_source(&source).is_err() {
            return;
        }
        // Explicit write grants intentionally override an earlier RO grant at
        // the same destination.  This is appended after all read mounts.
        self.explicit_rw_at(&source, path);
        if source != path {
            self.explicit_rw_at(&source, &source);
        }
    }

    fn rw(&mut self, source: &str, destination: &str) -> Result<(), String> {
        self.required_rw(source, destination)
    }
}

fn add_runtime_mounts(mounts: &mut MountPlan) {
    for raw in RUNTIME_DIRS {
        let Some(source) = canonical_existing(raw) else {
            continue;
        };
        if validate_mount_source(&source).is_err() {
            continue;
        }
        let raw_is_symlink =
            std::fs::symlink_metadata(raw).is_ok_and(|m| m.file_type().is_symlink());
        if raw_is_symlink && Path::new(&source).is_dir() {
            // Ubuntu's /lib and /lib64 are commonly symlinks into /usr.  A
            // second bind of the same source at the symlink path is rejected
            // by bwrap and can hide the first mount, so preserve the link in
            // the synthetic root instead.
            mounts.optional_ro(&source);
            if let Ok(target) = std::fs::read_link(raw) {
                let parent = Path::new(raw)
                    .parent()
                    .map_or_else(|| "/".to_string(), gopath::s);
                mounts.directory(&parent);
                mounts.args.extend([
                    "--symlink".into(),
                    target.to_string_lossy().into_owned(),
                    (*raw).into(),
                ]);
            }
        } else {
            mounts.optional_ro_at(&source, raw);
        }
    }
    for raw in RUNTIME_FILES {
        let Some(source) = canonical_existing(raw) else {
            continue;
        };
        if validate_mount_source(&source).is_ok() {
            mounts.optional_ro_at(&source, raw);
        }
    }
}

impl MountPlan {
    fn optional_ro_at(&mut self, source: &str, destination: &str) {
        if self.targets.contains(destination) || validate_mount_source(source).is_err() {
            return;
        }
        self.destination(source, destination);
        self.targets.insert(destination.into());
        self.args
            .extend(["--ro-bind-try".into(), source.into(), destination.into()]);
    }

    fn explicit_rw_at(&mut self, source: &str, destination: &str) {
        if validate_mount_source(source).is_err() || destination == "/" {
            return;
        }
        self.destination(source, destination);
        self.targets.insert(destination.into());
        self.args
            .extend(["--bind".into(), source.into(), destination.into()]);
    }
}

fn validate_mount_source(path: &str) -> Result<(), String> {
    if path == "/" {
        return Err("refusing to bind the host root into the sandbox".into());
    }
    let metadata = std::fs::metadata(path).map_err(|e| format!("{}: {e}", path))?;
    if !metadata.is_dir() && !metadata.is_file() {
        return Err(format!("refusing special-file sandbox mount {path}"));
    }
    let c_path = CString::new(path).map_err(|_| format!("sandbox path contains NUL: {path:?}"))?;
    // SAFETY: statfs writes only to the initialized output structure.
    let fs_type = unsafe {
        let mut stats: libc::statfs = std::mem::zeroed();
        if libc::statfs(c_path.as_ptr(), &mut stats) < 0 {
            return Err(format!(
                "inspect sandbox mount source {path}: {}",
                io::Error::last_os_error()
            ));
        }
        stats.f_type as i64
    };
    const PROC_SUPER_MAGIC: i64 = 0x9fa0;
    if fs_type == PROC_SUPER_MAGIC || (metadata.is_dir() && procfs_mount_below(path)?) {
        return Err(format!("refusing procfs-backed sandbox mount {path}"));
    }
    Ok(())
}

fn procfs_mount_below(path: &str) -> Result<bool, String> {
    let mountinfo = std::fs::read_to_string("/proc/self/mountinfo")
        .map_err(|e| format!("inspect /proc/self/mountinfo: {e}"))?;
    for line in mountinfo.lines() {
        let Some((left, right)) = line.split_once(" - ") else {
            continue;
        };
        let Some(mountpoint) = left.split_whitespace().nth(4) else {
            continue;
        };
        let Some(fs_name) = right.split_whitespace().next() else {
            continue;
        };
        if fs_name == "proc" {
            let mountpoint = mountinfo_unescape(mountpoint);
            if under(&mountpoint, path) {
                return Ok(true);
            }
        }
    }
    Ok(false)
}

fn mountinfo_unescape(path: &str) -> String {
    path.replace("\\040", " ")
        .replace("\\011", "\t")
        .replace("\\012", "\n")
        .replace("\\134", "\\")
}

fn canonical_existing(path: &str) -> Option<String> {
    std::fs::canonicalize(path).ok().map(|p| gopath::s(&p))
}

fn canonical_required(label: &str, path: &Path) -> Result<String, String> {
    let canonical =
        std::fs::canonicalize(path).map_err(|e| format!("{label} {}: {e}", path.display()))?;
    let value = gopath::s(&canonical);
    validate_mount_source(&value).map_err(|e| format!("{label}: {e}"))?;
    Ok(value)
}

fn manifest_path(raw: &str) -> Result<String, String> {
    let expanded = expand_home(raw);
    if gopath::is_abs(&expanded) {
        return Ok(gopath::clean(&expanded));
    }
    let cwd = std::env::current_dir().map_err(|e| format!("resolve manifest path {raw}: {e}"))?;
    Ok(gopath::s(&cwd.join(expanded)))
}

fn validate_optional_grant(path: &str) -> Result<(), String> {
    let Some(source) = canonical_existing(path) else {
        // Missing approved reads remain absent in the synthetic root; no host
        // parent is mounted to manufacture them.
        return Ok(());
    };
    validate_mount_source(&source)
}

fn under(path: &str, parent: &str) -> bool {
    path == parent || Path::new(path).strip_prefix(parent).is_ok()
}

fn script_interpreters(path: &Path) -> Result<Vec<(String, String)>, String> {
    let Ok(mut file) = File::open(path) else {
        return Ok(Vec::new());
    };
    let mut first = [0u8; 512];
    let Ok(n) = file.read(&mut first) else {
        return Ok(Vec::new());
    };
    let Ok(line) = std::str::from_utf8(&first[..n]) else {
        return Ok(Vec::new());
    };
    let Some(line) = line.lines().next().and_then(|line| line.strip_prefix("#!")) else {
        return Ok(Vec::new());
    };
    let mut words = line.split_whitespace();
    let Some(first) = words.next() else {
        return Ok(Vec::new());
    };
    if first == "/usr/bin/env" || first == "/bin/env" {
        return Err(format!(
            "Linux sandbox requires a script's real absolute interpreter, not {first}"
        ));
    }
    if !first.starts_with('/') {
        return Ok(Vec::new());
    }
    let source = canonical_existing(first)
        .ok_or_else(|| format!("script interpreter {first} does not exist"))?;
    Ok(vec![(source, first.to_string())])
}

fn duplicate_high(fd: RawFd) -> io::Result<OwnedFd> {
    let result = unsafe { libc::fcntl(fd, libc::F_DUPFD_CLOEXEC, FIRST_CHILD_FD) };
    if result < 0 {
        Err(io::Error::last_os_error())
    } else {
        // SAFETY: fcntl returned a new owned descriptor.
        Ok(unsafe { OwnedFd::from_raw_fd(result) })
    }
}

fn sealed_policy(policy: &Policy) -> io::Result<OwnedFd> {
    let name = c"rush-sandbox-policy";
    const MFD_CLOEXEC: libc::c_uint = 0x0001;
    const MFD_ALLOW_SEALING: libc::c_uint = 0x0002;
    // SAFETY: the name is NUL-terminated and the syscall returns a new fd.
    let raw = unsafe {
        libc::syscall(
            libc::SYS_memfd_create,
            name.as_ptr(),
            MFD_CLOEXEC | MFD_ALLOW_SEALING,
        )
    } as RawFd;
    if raw < 0 {
        return Err(io::Error::last_os_error());
    }
    // SAFETY: raw is the new descriptor returned by memfd_create.
    let mut file = unsafe { File::from_raw_fd(raw) };
    let payload = serde_json::to_vec(policy).map_err(io::Error::other)?;
    if payload.len() > MAX_POLICY_BYTES {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "sandbox policy is too large",
        ));
    }
    file.write_all(&payload)?;
    file.seek(SeekFrom::Start(0))?;
    const F_ADD_SEALS: libc::c_int = 1033;
    const F_SEAL_SEAL: libc::c_int = 0x0001;
    const F_SEAL_SHRINK: libc::c_int = 0x0002;
    const F_SEAL_GROW: libc::c_int = 0x0004;
    const F_SEAL_WRITE: libc::c_int = 0x0008;
    let seals = F_SEAL_SEAL | F_SEAL_SHRINK | F_SEAL_GROW | F_SEAL_WRITE;
    if unsafe { libc::fcntl(file.as_raw_fd(), F_ADD_SEALS, seals) } < 0 {
        return Err(io::Error::last_os_error());
    }
    let raw = file.into_raw_fd();
    // SAFETY: ownership of raw was returned by into_raw_fd.
    Ok(unsafe { OwnedFd::from_raw_fd(raw) })
}

fn read_policy() -> io::Result<Policy> {
    const F_GET_SEALS: libc::c_int = 1034;
    const F_SEAL_SEAL: libc::c_int = 0x0001;
    const F_SEAL_SHRINK: libc::c_int = 0x0002;
    const F_SEAL_GROW: libc::c_int = 0x0004;
    const F_SEAL_WRITE: libc::c_int = 0x0008;
    let seals = unsafe { libc::fcntl(BOOTSTRAP_FD, F_GET_SEALS) };
    let required = F_SEAL_SEAL | F_SEAL_SHRINK | F_SEAL_GROW | F_SEAL_WRITE;
    if seals < 0 || seals & required != required {
        return Err(io::Error::new(
            io::ErrorKind::PermissionDenied,
            "sandbox policy fd is not sealed",
        ));
    }
    let duplicate = duplicate_high(BOOTSTRAP_FD)?;
    let file = File::from(duplicate);
    let mut bytes = Vec::new();
    file.take((MAX_POLICY_BYTES + 1) as u64)
        .read_to_end(&mut bytes)?;
    if bytes.len() > MAX_POLICY_BYTES {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "sandbox policy is too large",
        ));
    }
    let policy: Policy = serde_json::from_slice(&bytes).map_err(io::Error::other)?;
    policy.validate()?;
    Ok(policy)
}

/// This constructor is linked after Rust's argv setup (`.init_array.00099`)
/// and before the unsuffixed test-environment constructor.  It does not call
/// `std::env::args`: raw `/proc/self/cmdline` is used because argv must not be
/// touched before the runtime's argv initialization.  The generated Linux
/// binaries are GNU-only and pin the constructor ordering in CI.
#[used]
#[cfg_attr(target_os = "linux", unsafe(link_section = ".init_array.00100"))]
static TRUSTED_BOOTSTRAP_INIT: extern "C" fn(
    libc::c_int,
    *const *const libc::c_char,
    *const *const libc::c_char,
) = trusted_bootstrap_init;

extern "C" fn trusted_bootstrap_init(
    _argc: libc::c_int,
    _argv: *const *const libc::c_char,
    _envp: *const *const libc::c_char,
) {
    match hidden_invocation() {
        Ok(InitMode::Bootstrap) => {
            if let Err(error) = trusted_bootstrap() {
                ctor_exit("rush: Linux sandbox bootstrap failed", &error, 127);
            }
        }
        Ok(InitMode::SeccompProbe) => {
            if let Err(error) = seccomp_probe() {
                ctor_exit("rush: Linux sandbox seccomp probe failed", &error, 127);
            }
            // The constructor runs before the Rust runtime has initialized;
            // _exit avoids invoking Rust atexit/runtime cleanup here.
            unsafe { libc::_exit(0) };
        }
        Ok(InitMode::None) | Err(_) => {}
    }
}

fn ctor_exit(prefix: &str, error: &dyn std::fmt::Display, status: libc::c_int) -> ! {
    let mut message = String::new();
    let _ = write!(&mut message, "{prefix}: {error}\n");
    let bytes = message.as_bytes();
    // SAFETY: fd 2 is the bootstrap's inherited stderr and the pointer/length
    // refer to a live immutable byte slice.
    unsafe {
        let _ = libc::write(2, bytes.as_ptr().cast(), bytes.len());
        libc::_exit(status);
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum InitMode {
    None,
    Bootstrap,
    SeccompProbe,
}

fn hidden_invocation() -> io::Result<InitMode> {
    let path = c"/proc/self/cmdline";
    // SAFETY: path is a valid NUL-terminated pathname and no inherited fd is
    // involved in determining whether this is the exact internal mode.
    let fd = unsafe { libc::open(path.as_ptr(), libc::O_RDONLY | libc::O_CLOEXEC) };
    if fd < 0 {
        return Err(io::Error::last_os_error());
    }
    let mut bytes = [0u8; 8192];
    let n = unsafe { libc::read(fd, bytes.as_mut_ptr().cast(), bytes.len()) };
    let error = if n < 0 {
        Some(io::Error::last_os_error())
    } else {
        None
    };
    // SAFETY: fd was opened above and is owned by this function.
    unsafe { libc::close(fd) };
    error.map_or_else(
        || {
            let bytes = &bytes[..n as usize];
            let mut args: Vec<&[u8]> = bytes.split(|byte| *byte == 0).collect();
            // /proc/self/cmdline normally ends with one NUL. Keep empty
            // arguments in the middle so hidden mode remains exact.
            if args.last().is_some_and(|arg| arg.is_empty()) {
                args.pop();
            }
            if args.len() != 2 {
                return Ok(InitMode::None);
            }
            if args[0] == BOOTSTRAP_PATH.as_bytes() && args[1] == BOOTSTRAP_ARG.as_bytes() {
                Ok(InitMode::Bootstrap)
            } else if args[0] == PROBE_PATH.as_bytes() && args[1] == PROBE_ARG.as_bytes() {
                Ok(InitMode::SeccompProbe)
            } else {
                Ok(InitMode::None)
            }
        },
        Err,
    )
}

fn seccomp_probe() -> io::Result<()> {
    let listener = seccomp::install(false)?;
    drop(listener);
    Ok(())
}

fn trusted_bootstrap() -> io::Result<()> {
    let policy = read_policy()?;
    let mut command = final_command(&policy)?;

    // Bubblewrap normally closes its setup descriptors before exec, but make
    // that boundary explicit: only stdio, the default IPC fd, the sealed
    // policy, and the control channel survive into the trusted bootstrap.
    // The policy reader's temporary high duplicate is already dropped here.
    close_unexpected_fds()?;

    // bwrap 0.9 brings private loopback up before handing control to the
    // command.  No network capability is therefore retained here; the bridge
    // only forks after dumpability/capabilities have already been reduced.
    set_nondumpable()?;
    drop_capabilities()?;
    transport::start_bridge(CONTROL_FD, policy.proxy_port)?;

    let listener = seccomp::install(policy.proxy_port != 0)?;
    transport::send_listener(CONTROL_FD, listener.as_raw_fd())?;
    drop(listener);
    close_fd(BOOTSTRAP_FD)?;
    close_fd(CONTROL_FD)?;

    // `Command::exec` performs the final execve in this process.  The policy's
    // environment has not been installed in the bootstrap; it is applied only
    // by this final exec, so LD_PRELOAD/GCONV_PATH cannot affect trusted code.
    let error = command.exec();
    Err(error)
}

fn close_unexpected_fds() -> io::Result<()> {
    // SAFETY: close_range operates only on this process's descriptor table;
    // descriptors 0..5 are deliberately retained for the bootstrap boundary.
    let result = unsafe { libc::syscall(libc::SYS_close_range, 6u32, u32::MAX, 0u32) };
    if result < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(())
    }
}

fn final_command(policy: &Policy) -> io::Result<Command> {
    let mut command = Command::new(&policy.program);
    command
        .arg0(&policy.argv[0])
        .args(&policy.argv[1..])
        .current_dir(&policy.current_dir)
        .env_clear();
    for (key, value) in &policy.env {
        command.env(key, value);
    }
    Ok(command)
}

fn set_nondumpable() -> io::Result<()> {
    // SAFETY: prctl operates only on this process and takes no pointers.
    if unsafe { libc::prctl(libc::PR_SET_DUMPABLE, 0, 0, 0, 0) } < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(())
    }
}

fn drop_capabilities() -> io::Result<()> {
    #[repr(C)]
    struct CapHeader {
        version: u32,
        pid: i32,
    }
    #[repr(C)]
    struct CapData {
        effective: u32,
        permitted: u32,
        inheritable: u32,
    }
    const LINUX_CAPABILITY_VERSION_3: u32 = 0x2008_0522;
    const PR_CAP_AMBIENT: libc::c_int = 47;
    const PR_CAP_AMBIENT_CLEAR_ALL: libc::c_int = 4;
    let mut header = CapHeader {
        version: LINUX_CAPABILITY_VERSION_3,
        pid: 0,
    };
    let mut data = [
        CapData {
            effective: 0,
            permitted: 0,
            inheritable: 0,
        },
        CapData {
            effective: 0,
            permitted: 0,
            inheritable: 0,
        },
    ];
    // SAFETY: the structures match linux_capability_header/data on the two
    // supported 64-bit GNU ABIs and remain alive for the syscall.
    if unsafe {
        libc::syscall(
            libc::SYS_capset,
            &mut header as *mut CapHeader,
            data.as_mut_ptr(),
        )
    } < 0
    {
        return Err(io::Error::last_os_error());
    }
    // SAFETY: no pointer arguments are used by PR_CAP_AMBIENT_CLEAR_ALL.
    if unsafe { libc::prctl(PR_CAP_AMBIENT, PR_CAP_AMBIENT_CLEAR_ALL, 0, 0, 0) } < 0 {
        return Err(io::Error::last_os_error());
    }
    Ok(())
}

fn close_fd(fd: RawFd) -> io::Result<()> {
    // SAFETY: the bootstrap owns these fixed descriptors and closes each once.
    if unsafe { libc::close(fd) } < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(())
    }
}
