//! Linux plugin launcher and its trusted, pre-plugin bootstrap.
//!
//! After internal/plugin/sandbox.go:24 and sandbox_darwin.go:28 in the
//! Go reference. The Linux launcher deliberately keeps the
//! host environment out of bubblewrap: the only environment a plugin receives
//! is carried in the sealed policy consumed by the bootstrap immediately
//! before the approved program is `exec`'d.

